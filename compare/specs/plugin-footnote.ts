/**
 * Normalize the footnote markup so that the remaining comparison covers behavior
 *
 * The current package emits an extra empty `<a class="footnote-anchor">` element inside the
 * reference marker, and prefixes its generated ids with `footnote` instead of `fn`. Both are purely
 * structural: the element only exists so that consumers can add a CSS scroll offset, and the ids
 * are generated by the plugin in both implementations.
 *
 * @param html - Rendered HTML
 * @returns Normalized HTML
 */
const normalizeFootnoteHtml = composeNormalizers(
  (html) => removeMatches(html, /<a class="footnote-anchor" id="[^"]*"><\/a>/gu),
  (html) => removeMatches(html, / id="fnref[^"]*"/gu),
  (html) => replaceMatches(html, /footnote-ref(?<id>\d+(?::\d+)?)/gu, "fnref$<id>"),
  (html) => replaceMatches(html, /footnote(?<id>\d+(?::\d+)?)/gu, "fn$<id>"),
  sortAttributes,
);

