import type { Token } from "markdown-it";

/**
 * Check whether an attribute name can be safely emitted into HTML.
 *
 * Attribute names are interpolated as-is by `renderAttrs`, so names containing whitespace or quotes
 * could inject extra attributes. Such names are ignored.
 *
 * @param name - Attribute name / 属性名
 * @returns Whether the name is safe / 是否安全
 */
const isValidAttributeName = (name: string): boolean => {
  if (name.length === 0) return false;

  for (let index = 0; index < name.length; index++) {
    const charCode = name.charCodeAt(index);

    // control characters, whitespace, `"`, `'`, `/`, `<`, `=`, `>`
    if (
      charCode <= 32 ||
      charCode === 34 /* " */ ||
      charCode === 39 /* ' */ ||
      charCode === 47 /* / */ ||
      charCode === 60 /* < */ ||
      charCode === 61 /* = */ ||
      charCode === 62 /* > */
    )
      return false;
  }

  return true;
};

/**
 * Escape a value for a double-quoted HTML attribute.
 *
 * Every generated attribute is double-quoted, so apostrophes are kept as-is, matching how
 * markdown-it escapes `token.attrs`. `&`, `<`, `>` and `"` are escaped so a caller-provided value
 * cannot break out of the attribute or inject markup.
 *
 * @param value - Raw attribute value / 原始属性值
 * @returns Escaped attribute value / 转义后的属性值
 */
export const escapeAttribute = (value: string): string => {
  let result = "";
  let lastIndex = 0;

  for (let index = 0; index < value.length; index++) {
    let replacement = "";

    switch (value.charCodeAt(index)) {
      case 34 /* " */: {
        replacement = "&quot;";
        break;
      }
      case 38 /* & */: {
        replacement = "&amp;";
        break;
      }
      case 60 /* < */: {
        replacement = "&lt;";
        break;
      }
      case 62 /* > */: {
        replacement = "&gt;";
        break;
      }
      default: {
        break;
      }
    }

    if (replacement) {
      result += value.slice(lastIndex, index) + replacement;
      lastIndex = index + 1;
    }
  }

  return lastIndex === 0 ? value : result + value.slice(lastIndex);
};

/**
 * Apply user-provided attributes to a token.
 *
 * `class` is joined with the generated class, any other attribute overrides the generated value.
 * Invalid attribute names are ignored.
 *
 * @param token - Target token / 目标 token
 * @param attrs - Attributes to apply / 要应用的属性
 */
export const applyAttrs = (token: Token, attrs?: Record<string, string | number>): void => {
  if (!attrs) return;

  for (const [name, value] of Object.entries(attrs)) {
    if (!isValidAttributeName(name)) continue;

    if (name === "class") {
      const className = String(value).trim();

      if (className) token.attrJoin("class", className);
    } else {
      token.attrSet(name, value);
    }
  }
};

/**
 * Get the id suffix of duplicated footnote references.
 *
 * @param subId - Index of duplicated references / 重复引用的索引
 * @returns `:${subId}` for duplicated references, otherwise an empty string / 重复引用时为
 *   `:${subId}`，否则为空字符串
 */
export const getFootnoteSuffix = (subId?: number): string => ((subId ?? 0) > 0 ? `:${subId}` : "");

/**
 * Get the anchor name used by generated ids and hrefs.
 *
 * The footnote number is generated by the plugin and always starts from `1`. When `docId` is
 * provided, it is prefixed so multiple documents on the same page do not share anchors. The values
 * are kept raw here and escaped by the renderer.
 *
 * @param docId - Document id from the render env / 渲染环境中的文档 id
 * @param id - Zero-based footnote index / 从 0 开始的脚注索引
 * @returns Raw anchor name / 原始锚点名
 */
export const getFootnoteAnchorName = (docId: string | null | undefined, id: number): string =>
  `${typeof docId === "string" ? `-${docId}-` : ""}${id + 1}`;

/**
 * Get the caption of a footnote reference.
 *
 * @param id - Zero-based footnote index / 从 0 开始的脚注索引
 * @param subId - Index of duplicated references / 重复引用的索引
 * @returns Caption like `[1]` or `[1:1]` / 类似 `[1]` 或 `[1:1]` 的标题
 */
export const getFootnoteCaption = (id: number, subId?: number): string =>
  `[${id + 1}${getFootnoteSuffix(subId)}]`;
