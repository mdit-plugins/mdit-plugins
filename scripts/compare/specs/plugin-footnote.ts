import { composeNormalizers, removeMatches, replaceMatches, sortAttributes } from "../normalize.ts";
import type { ComparisonSpec } from "../types.ts";
import { defineComparison } from "../types.ts";

/** Markdown with a sparse amount of footnote syntax, close to a normal document */
const NORMAL_UNIT = `## Notes

A paragraph that references a footnote[^note] and keeps the surrounding text long enough to look realistic.

Another paragraph without any footnote syntax at all.

- a list item
- another item

[^note]: The footnote definition text.

`;

/** Markdown where most paragraphs carry footnote references and definitions */
const HEAVY_UNIT = `Text with a reference[^a] and a duplicate[^a] plus an inline note^[Inline footnote text].

Another line referencing[^b], again[^b] and a third footnote[^c] and another inline^[More *markup* here].

[^a]: First footnote definition.

[^b]: Second footnote **definition** with markup.

[^c]: Third footnote definition.

`;

/** Repetitions of the benchmark units, tuned to roughly 1-3 KB, 8-15 KB and 30-50 KB */
const REPETITIONS = {
  normal: { small: 5, medium: 36, large: 150 },
  heavy: { small: 5, medium: 30, large: 120 },
} as const;

/**
 * Build a benchmark corpus from the unit of the requested kind
 *
 * @param kind - Corpus kind
 * @param size - Corpus size
 * @returns Markdown of the requested size
 */
const buildCorpus = (kind: "normal" | "heavy", size: "small" | "medium" | "large"): string =>
  (kind === "normal" ? NORMAL_UNIT : HEAVY_UNIT).repeat(REPETITIONS[kind][size]);

const BENCH_CASES = (["normal", "heavy"] as const).flatMap((kind) =>
  (["small", "medium", "large"] as const).map((size) => ({
    name: `${kind}/${size}`,
    kind,
    size,
    markdown: buildCorpus(kind, size),
  })),
);

/**
 * Normalize the footnote markup so that the remaining comparison covers behavior
 *
 * The current package emits an extra empty `<a class="footnote-anchor">` element inside the
 * reference marker, and prefixes its generated ids with `footnote` instead of `fn`. Both are purely
 * structural: the element only exists so that consumers can add a CSS scroll offset, and the ids
 * are generated by the plugin in both implementations.
 *
 * @param html - Rendered HTML
 * @returns Normalized HTML
 */
const normalizeFootnoteHtml = composeNormalizers(
  (html) => removeMatches(html, /<a class="footnote-anchor" id="[^"]*"><\/a>/gu),
  (html) => removeMatches(html, / id="fnref[^"]*"/gu),
  (html) => replaceMatches(html, /footnote-ref(?<id>\d+(?::\d+)?)/gu, "fnref$<id>"),
  (html) => replaceMatches(html, /footnote(?<id>\d+(?::\d+)?)/gu, "fn$<id>"),
  sortAttributes,
);

